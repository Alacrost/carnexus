  const saleReq=randomUUID(); const deal=await cmd('sale',null,sale,saleReq);
  await cmd('status',deal.id,{status:'agreed'});
  assert.equal((await cmd('sale',null,sale,saleReq)).id,deal.id);
  await assert.rejects(()=>cmd('sale',null,sale),/vehicle_has_open_deal/);
  await assert.rejects(()=>cmd('price',deal.id,{price:14000,version:1,reason:'Discount'}),/commercial_not_allowed/);
