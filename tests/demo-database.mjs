import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {openDemoDatabase,demoEntityId} from '../src/lib/demo-database.mjs';
import {loadVehicleSales,isOpenVehicleDeal} from '../src/lib/vehicle-sales.ts';
import {demoSession,demoVehicles,demoCustomers,demoStaff,demoLeads} from '../src/lib/demo.ts';

const directory=await mkdtemp(join(tmpdir(),'autonexus-demo-test-'));
const options={dataDir:directory,migrationsDir:resolve('supabase/migrations'),seed:{ownerId:demoSession.userId,dealerId:demoSession.dealer.id,vehicles:demoVehicles,customers:demoCustomers,staff:demoStaff,leads:demoLeads}};
let db;
const rpc=async(name,args)=>{const result=await db.rpc(name,args);assert.equal(result.error,null,JSON.stringify(result.error));return result.data;};
const command=(command,entity,data)=>rpc('commercial_command',{p_dealer:demoSession.dealer.id,p_command:command,p_id:entity,p_input:data,p_request:randomUUID()});
try{
  await assert.rejects(()=>openDemoDatabase({...options,dataDir:'postgres://example.invalid/demo'}),/local directory/);
  db=await openDemoDatabase(options);
  assert.equal(typeof (await db.from('vehicles').select('sale_price').eq('id',demoEntityId('v1')).single()).data.sale_price,'number');
  const customer=await rpc('save_deal_customer',{p_dealer:demoSession.dealer.id,p_input:{name:'Local persistence test',type:'individual',email:'local@example.test',address:'Test address only'},p_request:randomUUID()});
  const snapshot={sale:{customerId:customer.id,vehicleId:demoEntityId('v1'),salespersonId:demoSession.userId,locationId:'',leadId:'',source:'walk_in',salePrice:17950,vatScheme:'standard',priceReason:'',notes:''},terms:{quoteTerms:'Valid for test only',notes:'',financeTerms:'',warrantyId:''},deposits:[],trades:[],agreement:false};
  const input={p_dealer:demoSession.dealer.id,p_session:randomUUID(),p_revision:0,p_input:snapshot,p_request:randomUUID()};
  const saved=await rpc('autosave_new_deal',input);
  assert.equal(saved.status,'vehicle_interest');
  const interestRows=await loadVehicleSales(db,demoSession.dealer.id,demoEntityId('v1'));
  assert.equal(interestRows.length,1);
  assert.equal(interestRows[0].id,saved.id);
  assert.equal(interestRows[0].customer.name,'Local persistence test');
  assert.equal(isOpenVehicleDeal(interestRows[0].status),true);
  assert.equal((await loadVehicleSales(db,demoSession.dealer.id,demoEntityId('v4'))).length,0);
  assert.deepEqual(['completed','cancelled','reversed'].map(isOpenVehicleDeal),[false,false,false]);
  const duplicateInput={...input,p_session:randomUUID(),p_request:randomUUID(),p_input:{...snapshot,deposits:[{amount:200,method:'cash',paidOn:new Date().toISOString().slice(0,10)}]}};
  const duplicate=await rpc('autosave_new_deal',duplicateInput);
  assert.deepEqual(duplicate,{existingDeal:{id:saved.id,number:saved.number,status:'vehicle_interest'}});
  assert.deepEqual(await rpc('autosave_new_deal',duplicateInput),duplicate,'duplicate-session retry returns the same existing Deal');
  assert.equal((await db.from('payments').select('id').eq('deal_id',saved.id)).data.length,0,'reusing an existing Deal must not apply the new session deposit');
  const otherCustomer=await rpc('save_deal_customer',{p_dealer:demoSession.dealer.id,p_input:{name:'Local persistence test',type:'individual'},p_request:randomUUID()});
  assert.notEqual(otherCustomer.id,customer.id,'a matching name is not a customer identity');
  const secondInterest=await rpc('autosave_new_deal',{...input,p_session:randomUUID(),p_request:randomUUID(),p_input:{...snapshot,sale:{...snapshot.sale,customerId:otherCustomer.id}}});
  assert.notEqual(secondInterest.id,saved.id);
  assert.equal((await loadVehicleSales(db,demoSession.dealer.id,demoEntityId('v1'))).filter(row=>isOpenVehicleDeal(row.status)).length,2);
  assert.deepEqual(await rpc('autosave_new_deal',input),saved,'retry must not duplicate');
  assert.equal((await db.from('vehicles').select('status').eq('id',demoEntityId('v1')).single()).data.status,'ready_for_sale');
  const quote=await command('document',saved.id,{kind:'quote'});
  const quoteDoc=await db.from('deal_documents').select('snapshot').eq('id',quote.id).single();
  assert.equal(quoteDoc.data.snapshot.kind,'quote');
  const dates=await db.from('deal_documents').select('effective_date,created_at').eq('id',quote.id).single();
  assert.match(dates.data.effective_date,/^\d{4}-\d{2}-\d{2}$/);
  assert.equal(typeof dates.data.created_at,'string');
  assert.match(quoteDoc.data.snapshot.dealer.legal_name,/TEST ONLY/);
  await db.close();db=await openDemoDatabase(options);
  assert.equal((await db.from('customers').select('name').eq('id',customer.id).single()).data.name,'Local persistence test');
  assert.equal((await db.from('deals').select('status').eq('id',saved.id).single()).data.status,'vehicle_interest');
  const agreement=await rpc('autosave_new_deal',{...input,p_revision:saved.revision,p_request:randomUUID(),p_input:{...snapshot,agreement:true}});
  assert.equal(agreement.status,'agreed');assert.ok(agreement.documentId);
  const linked=await loadVehicleSales(db,demoSession.dealer.id,demoEntityId('v1'));
  assert.equal(linked.find(row=>row.id===agreement.id).status,'agreed');
  assert.ok(linked.every(row=>row.stage));
  assert.equal((await db.from('vehicles').select('status').eq('id',demoEntityId('v1')).single()).data.status,'reserved');
  await db.close();db=await openDemoDatabase(options);
  assert.equal((await db.from('deal_documents').select('snapshot').eq('id',agreement.documentId).single()).data.snapshot.kind,'agreement');
  const timeline=await rpc('customer_timeline',{p_dealer:demoSession.dealer.id,p_customer:customer.id,p_before:null,p_before_id:null,p_limit:30,p_kinds:['document']});
  assert.ok(timeline.items.length>=2);
  assert.equal(await rpc('vehicle_purchase_ready',{p_dealer:demoSession.dealer.id,p_vehicle:demoEntityId('v1')}),false,'demo must not bypass missing PO');
  const deposit=await rpc('autosave_new_deal',{...input,p_session:randomUUID(),p_request:randomUUID(),p_input:{...snapshot,sale:{...snapshot.sale,vehicleId:demoEntityId('v2'),salePrice:28500},deposits:[{amount:200,method:'cash',paidOn:new Date().toISOString().slice(0,10)}]}});
  assert.equal(deposit.status,'agreed');assert.ok(deposit.documentId);
  console.log('PASS local demo: customer, autosave/replay, quote, explicit agreement, deposit trigger, persisted reopen and PO guard');
}finally{if(db)await db.close();await rm(directory,{recursive:true,force:true});}
